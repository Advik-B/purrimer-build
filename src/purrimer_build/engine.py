"""Rendering engine: one Jinja2 environment per target, shared filters and the output writer."""

from __future__ import annotations

import json
import pprint
from collections.abc import Callable
from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path

import jinja2

from .components import Component
from .fonts import StaticFont, WebFont
from .model import Tokens
from .motion import Catalog, burst_particles, burst_python
from .naming import camel, kebab, num, pascal, snake

GENERATED_NOTE = "Generated by purrimer-build from tokens.json. Do not edit by hand."


def package_templates() -> Path:
    return Path(str(resources.files("purrimer_build") / "templates"))


def load_octicons() -> dict[str, dict[str, str]]:
    raw = json.loads((resources.files("purrimer_build") / "data" / "octicons.json").read_text(encoding="utf-8"))
    return {name: {size: " ".join(paths) for size, paths in sizes.items()} for name, sizes in raw.items()}


@dataclass
class Build:
    tokens: Tokens
    components: list[Component]
    out: Path
    component_roots: list[Path]
    web_fonts: list[WebFont] = field(default_factory=list)
    static_fonts: list[StaticFont] = field(default_factory=list)
    written: list[Path] = field(default_factory=list)
    icons: dict[str, dict[str, str]] = field(default_factory=load_octicons)
    motion: Catalog = field(default_factory=Catalog.load)

    def environment(
        self, filters: dict[str, Callable] | None = None, globals_: dict | None = None
    ) -> jinja2.Environment:
        components_loader = jinja2.ChoiceLoader([jinja2.FileSystemLoader(str(r)) for r in self.component_roots])
        loader = jinja2.PrefixLoader(
            {
                "c": components_loader,
                "t": jinja2.FileSystemLoader(str(package_templates())),
            }
        )
        env = jinja2.Environment(
            loader=loader,
            undefined=jinja2.StrictUndefined,
            trim_blocks=True,
            lstrip_blocks=True,
            keep_trailing_newline=True,
            autoescape=False,
            # Svelte uses {#if} blocks, so Jinja comments are {## ... ##} instead of {# ... #}.
            comment_start_string="{##",
            comment_end_string="##}",
        )
        env.filters.update(
            {
                "camel": camel,
                "pascal": pascal,
                "kebab": kebab,
                "snake": snake,
                "num": num,
                "tojson": lambda v, indent=None: json.dumps(v, indent=indent, ensure_ascii=False),
                "py": lambda v: pprint.pformat(v, width=120, sort_dicts=False),
            }
        )
        env.globals.update(
            {
                "note": GENERATED_NOTE,
                "tokens": self.tokens,
                "themes": self.tokens.themes,
                "labels": self.tokens.theme_labels,
                "components": self.components,
                "icon_path": self.icon_path,
                "px": self.px,
                "ms": self.ms,
                "motion": self.motion,
                "burst_python": burst_python,
                "burst_particles": burst_particles,
                "color_hex": {n: {t: c.rgba_hex() for t, c in v.items()} for n, v in self.tokens.colors.items()},
                "color_argb": {n: {t: c.argb_hex() for t, c in v.items()} for n, v in self.tokens.colors.items()},
            }
        )
        if filters:
            env.filters.update(filters)
        if globals_:
            env.globals.update(globals_)
        return env

    def icon_path(self, name: str, size: int = 16) -> str:
        try:
            sizes = self.icons[name]
        except KeyError:
            raise KeyError(f"Unknown Octicon: {name}") from None
        key = str(size)
        if key not in sizes:
            key = next(iter(sizes))
        return sizes[key]

    def px(self, name: str) -> float:
        return self.tokens.length_map[name]

    def ms(self, name: str) -> int:
        return self.tokens.duration_map[name]

    def write(self, rel: str, text: str) -> None:
        path = self.out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        self.written.append(path)

    def render(self, env: jinja2.Environment, template: str, rel: str, **ctx) -> str:
        text = env.get_template(template).render(**ctx)
        self.write(rel, text)
        return text


def checked(tokens: Tokens, fn: Callable[[str], str]) -> Callable[[str], str]:
    """Wraps a token-reference filter so an unknown token name fails the build."""

    def inner(name: str) -> str:
        tokens.kind(name)
        return fn(name)

    return inner
